#!/usr/bin/env python3
"""The one MCP tool this collection ships: `query`, over the p8ql dialect.

    python3 query_mcp.py --port 8090 --postgrest http://localhost:3000

Why an MCP server at all, when `POST /rpc/query` already exists and the
OpenAPI adapter could bind it? Because binding it that way produces a tool
called `post_rpc_query` taking `p_query: string`, sitting in a list of thirty
other `post_rpc_*` operations, with nothing to say what a p8ql string looks
like. The dialect is one string argument whose whole difficulty is its
grammar, and MCP is where that grammar can be the tool's description. Same
endpoint underneath; the difference is entirely what the model is told.

Three properties this is the reference for:

1.  **No tool logic.** It forwards to `aiq.query` and returns what came back.
    There is no retrieval code here, no ranking, no query building -- the
    nine modes live in SQL (`specs/ai-query-layer/schema.sql`) and this file
    is a transport in front of them.

2.  **The description is fetched, not written.** `tools/list` builds the
    description from `SCHEMA "p8ql"` -- the dialect facet, whose examples the
    parser re-verifies on every read. So the tool documentation a model sees
    is generated by the database at the moment it is asked, and a deployment
    with different sources registered advertises different ones. Nothing here
    restates the grammar, which means nothing here can fall behind it.

3.  **Identity is the caller's.** The `Authorization` header on the MCP
    request is forwarded verbatim to PostgREST; this process holds no
    credential of its own and can read nothing on its own behalf. Whatever RLS
    would do to the user calling the agent, it does to the tool call
    (brief.md §11.1) -- a tool server that authenticated as itself would hand
    every user the same, maximal, result set.

Standard library only, and deliberately: a tool server whose whole job is to
forward one JSON body should not drag a dependency tree into the deployment.
"""
import argparse
import json
import urllib.error
import urllib.request
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

# The protocol revision this speaks. Sent back on initialize; a client asking
# for a different one is answered with what we actually implement rather than
# with an error, which is what the spec asks for.
PROTOCOL_VERSION = "2025-06-18"

# The one thing said here that the database cannot say for itself: what this
# tool is FOR. Everything below the marker is fetched at list time.
#
# It used to name the modes in prose as well -- "name lookup, graph traversal,
# lexical search, ..." -- and still said seven of them after RELEVANCE and PATH
# shipped, so the one sentence a model reads before deciding whether to use this
# tool described a smaller tool than the grammar underneath it. The list is now
# filled in from the same `SCHEMA "p8ql"` read that builds the rest, which is
# the only way it stays true: a mode reaches the prompt because the parser emits
# it, not because somebody remembered this file.
TOOL_PREAMBLE = """\
Ask this database a question in p8ql, its query dialect. One string, one
endpoint, every retrieval mode: %s.

The response carries the parsed `plan` next to the `rows`, so a query that was
understood differently than intended is visible rather than looking like an
empty result. Read the plan when rows come back empty.

The grammar and the currently registered sources follow, emitted by the parser
and the live schema at the moment you were given this tool:
"""


class Upstream:
    """PostgREST, called with the caller's own credentials."""

    def __init__(self, base):
        self.base = base.rstrip("/")

    def rpc(self, fn, payload, authorization=None):
        req = urllib.request.Request(
            f"{self.base}/rpc/{fn}",
            data=json.dumps(payload).encode(),
            method="POST",
            headers={
                "Content-Type": "application/json",
                # aiq is not PostgREST's default schema, so every call names
                # it. Same fact that put `default_headers` on tool_servers.
                "Accept-Profile": "aiq",
                "Content-Profile": "aiq",
                **({"Authorization": authorization} if authorization else {}),
            },
        )
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.loads(r.read() or b"null"), None
        except urllib.error.HTTPError as e:
            body = e.read().decode(errors="replace")
            try:
                body = json.loads(body)
            except ValueError:
                pass
            return None, {"kind": "tool_error", "status": e.code, "body": body}
        except (urllib.error.URLError, TimeoutError, OSError) as e:
            # brief.md §5.2 keeps these two apart: "the tool ran and said no"
            # and "the tool was unreachable" are different facts, and the
            # second one is not something the model should retry differently.
            return None, {"kind": "dispatch_error", "detail": str(e)}


def describe_query_tool(up, authorization):
    """The tool definition -- description built from SCHEMA "p8ql"."""
    doc, err = up.rpc("query", {"p_query": 'SCHEMA "p8ql"'}, authorization)
    if err:
        # A tool server that refuses to list its tools because one lookup
        # failed is worse than one that lists them with a thinner description:
        # the agent loses the capability entirely rather than some prose.
        detail = "(the live dialect schema could not be read: %s)" % (
            err.get("detail") or err.get("status"))
    else:
        detail = json.dumps(doc.get("schema", {}).get("doc", {}), indent=1)
    # If the fetch failed there is no mode list to name, and inventing one here
    # is how this went wrong the first time.
    modes = [m["mode"] for m in
             (doc or {}).get("schema", {}).get("doc", {})
             .get("declared", {}).get("modes", [])] if not err else []
    preamble = TOOL_PREAMBLE % (", ".join(modes) if modes
                                else "see the grammar below")
    return {
        "name": "query",
        "title": "Query the Percolate knowledge base",
        "description": preamble + "\n" + detail,
        "inputSchema": {
            "type": "object",
            "properties": {
                "query": {
                    "type": "string",
                    "description": "One p8ql statement. See the modes above.",
                }
            },
            "required": ["query"],
            "additionalProperties": False,
        },
    }


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    upstream = None

    def log_message(self, fmt, *args):
        print("[query-mcp] %s" % (fmt % args), flush=True)

    # -- JSON-RPC plumbing -------------------------------------------------

    def _send(self, code, payload):
        body = b"" if payload is None else json.dumps(payload).encode()
        self.send_response(code)
        if body:
            self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        if body:
            self.wfile.write(body)

    def _result(self, rid, result):
        self._send(200, {"jsonrpc": "2.0", "id": rid, "result": result})

    def _error(self, rid, code, message):
        self._send(200, {"jsonrpc": "2.0", "id": rid,
                         "error": {"code": code, "message": message}})

    def do_GET(self):
        # The GET half of streamable HTTP opens a server-to-client event
        # stream. Nothing here ever pushes, so saying so is more honest than
        # holding a connection open forever.
        self._send(405, {"error": "this server does not initiate messages"})

    def do_POST(self):
        try:
            n = int(self.headers.get("Content-Length") or 0)
            msg = json.loads(self.rfile.read(n) or b"{}")
        except ValueError:
            return self._error(None, -32700, "parse error")

        rid, method = msg.get("id"), msg.get("method")
        auth = self.headers.get("Authorization")

        # A notification carries no id and gets no response body.
        if rid is None and method and method.startswith("notifications/"):
            return self._send(202, None)

        if method == "initialize":
            return self._result(rid, {
                "protocolVersion": PROTOCOL_VERSION,
                "capabilities": {"tools": {"listChanged": False}},
                "serverInfo": {"name": "p8-query", "version": "0.1.0"},
                "instructions":
                    "One tool. Ask the knowledge base in p8ql; read the "
                    "returned plan to confirm the query was understood.",
            })

        if method == "ping":
            return self._result(rid, {})

        if method == "tools/list":
            return self._result(rid, {
                "tools": [describe_query_tool(self.upstream, auth)]})

        if method == "tools/call":
            params = msg.get("params") or {}
            if params.get("name") != "query":
                return self._error(rid, -32602,
                                   "unknown tool: %r" % params.get("name"))
            q = (params.get("arguments") or {}).get("query")
            if not isinstance(q, str) or not q.strip():
                # Reported as a tool result rather than a protocol error: the
                # model wrote a bad argument, which is an observation it can
                # act on, not a transport failure.
                return self._result(rid, {
                    "isError": True,
                    "content": [{"type": "text",
                                 "text": "query must be a non-empty string"}]})

            doc, err = self.upstream.rpc("query", {"p_query": q}, auth)
            if err:
                return self._result(rid, {
                    "isError": True,
                    "_meta": {"errorKind": err["kind"]},
                    "content": [{"type": "text", "text": json.dumps(err)}]})
            return self._result(rid, {
                "content": [{"type": "text", "text": json.dumps(doc)}],
                # The half a citation-extracting runtime reads (brief §5.3):
                # the rows this query actually returned, not a restatement.
                "structuredContent": doc,
            })

        return self._error(rid, -32601, "unknown method: %r" % method)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--port", type=int, default=8090)
    ap.add_argument("--host", default="0.0.0.0")
    ap.add_argument("--postgrest", default="http://localhost:3000")
    a = ap.parse_args()
    Handler.upstream = Upstream(a.postgrest)
    print(f"[query-mcp] http://{a.host}:{a.port}  ->  {a.postgrest}", flush=True)
    ThreadingHTTPServer((a.host, a.port), Handler).serve_forever()


if __name__ == "__main__":
    main()
